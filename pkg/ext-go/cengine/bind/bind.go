// Package bind generates a typed Go binding of a library of lib/ from the description of its
// interface (library.Description: lib/plugin's interface.json, served by describe). The generated
// code is a thin layer over cengine/library's described runtime: a type for each kind of object, a
// method for each operation, a struct of handlers for each object's events and for a call's own, and
// struct types where the description's JSON Schemas name properties. It knows no library: whatever a
// description says is what it generates.
//
// `ext lib bind` runs it from a project's go generate (cengine/libcmd).
package bind

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strings"
	"unicode"

	"github.com/webong/ext/pkg/ext-go/cengine/library"
)

// Options says what to generate.
type Options struct {
	// Package is the Go package name of the generated file.
	Package string
	// Source names where the description came from, for the generated file's header.
	Source string
}

var identifier = regexp.MustCompile(`^[a-z][a-z0-9]*$`)

// Generate returns the Go source of a binding of d.
func Generate(d library.Description, o Options) ([]byte, error) {
	if !identifier.MatchString(o.Package) {
		return nil, fmt.Errorf("bind: package name %q", o.Package)
	}
	if d.Library == "" || d.ABIVersion == 0 {
		return nil, errors.New("bind: the description names no library or ABI version")
	}
	root, ok := d.Objects["library"]
	if !ok {
		return nil, errors.New("bind: the description has no library object")
	}
	g := &generator{d: d, types: map[string]string{}}
	g.printf("// Code generated by \"ext lib bind\" from the description of %s (ABI %d)", d.Library, d.ABIVersion)
	if o.Source != "" {
		g.printf(" in %s", o.Source)
	}
	g.printf(". DO NOT EDIT.\n\n")
	if d.About != "" {
		g.comment("", "Package "+o.Package+" is the generated binding of "+d.Library+": "+d.About)
	}
	g.printf("package %s\n\n", o.Package)
	g.printf("import (\n\t\"encoding/json\"\n\n\t\"github.com/webong/ext/pkg/ext-go/cengine/library\"\n)\n\n")
	g.printf("var _ json.RawMessage\n\n")
	g.printf("// Prefix and ABIVersion name the library interface this binding was generated from.\n")
	g.printf("const (\n\tPrefix = %q\n\tABIVersion = %d\n)\n\n", d.Library, d.ABIVersion)

	g.comment("", "Library is handle 0 of "+d.Library+", the library itself."+aboutSuffix(root.About))
	g.printf("type Library struct {\n\td *library.Described\n\to *library.Object\n}\n\n")
	g.printf("// Bind binds %s's interface in lib and reads its description.\n", d.Library)
	g.printf("func Bind(lib *library.Library) (*Library, error) {\n")
	g.printf("\tifc, err := library.BindInterface(lib, Prefix, ABIVersion)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	g.printf("\td, err := library.Describe(ifc)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	g.printf("\treturn &Library{d: d, o: d.Library()}, nil\n}\n\n")
	g.printf("// Described is the library's own description, as the library serves it.\n")
	g.printf("func (x *Library) Described() *library.Described { return x.d }\n\n")
	g.operations("Library", "library", root)

	for _, kind := range sortedKeys(d.Objects) {
		if kind == "library" {
			continue
		}
		about := d.Objects[kind]
		name := goName(kind)
		g.comment("", name+" is a "+kind+" object of "+d.Library+"."+aboutSuffix(about.About))
		g.printf("type %s struct{ o *library.Object }\n\n", name)
		config := g.schemaType(name+"Config", about.Config, true)
		if len(about.Events) > 0 {
			g.handlers(name+"Handlers", "the events of a "+kind, about.Events, sortedKeys(about.Events))
			g.printf("// Open%s opens a %s, with handlers for its events; an event without one is denied (or, when\n// it asks nothing, dropped).\n", name, kind)
			g.printf("func (x *Library) Open%s(config %s, handlers %sHandlers) (*%s, error) {\n", name, config, name, name)
			g.printf("\to, err := x.d.Open(%q, config, handlers.handlers())\n", kind)
		} else {
			g.printf("// Open%s opens a %s.\n", name, kind)
			g.printf("func (x *Library) Open%s(config %s) (*%s, error) {\n", name, config, name)
			g.printf("\to, err := x.d.Open(%q, config, nil)\n", kind)
		}
		g.printf("\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn &%s{o}, nil\n}\n\n", name)
		g.printf("// Close closes the %s.\nfunc (x *%s) Close() error { return x.o.Close() }\n\n", kind, name)
		g.operations(name, kind, about)
	}
	g.body.WriteString(g.decls.String())
	out, err := format.Source(g.body.Bytes())
	if err != nil {
		return nil, fmt.Errorf("bind: the generated code does not parse: %w", err)
	}
	return out, nil
}

type generator struct {
	d     library.Description
	body  bytes.Buffer
	decls bytes.Buffer      // the struct types, after the methods
	types map[string]string // generated type names, so each is made once
}

func (g *generator) printf(format string, args ...any) { fmt.Fprintf(&g.body, format, args...) }

func (g *generator) comment(indent, text string) {
	for _, line := range wrap(text, 96) {
		g.printf("%s// %s\n", indent, line)
	}
}

// operations writes a method for each operation of an object.
func (g *generator) operations(receiver, kind string, about library.ObjectDescription) {
	for _, op := range sortedKeys(about.Operations) {
		od := about.Operations[op]
		method := goName(op)
		if method == "Close" || method == "Open" || method == "Described" {
			method += "Operation"
		}
		in := g.schemaType(receiver+method+"Input", od.Input, false)
		out := g.schemaType(receiver+method+"Output", od.Output, false)
		inArg := "in " + in
		call := "in"
		if in == "json.RawMessage" {
			call = "raw(in)"
			g.ensureRaw()
		}
		doc := method + " runs " + op + " on the " + kind + "." + aboutSuffix(od.About)
		g.method(receiver, method, inArg, out, kind, op, call, "", doc)
		var raises []string
		for _, e := range od.Raises {
			if _, ok := about.Events[e]; ok {
				raises = append(raises, e)
			}
		}
		if len(raises) > 0 {
			handlers := receiver + method + "Handlers"
			g.handlers(handlers, "the events "+op+" raises for one call", about.Events, raises)
			g.method(receiver, method+"With", inArg+", handlers "+handlers, out, kind, op, call, "handlers.handlers()",
				method+"With is "+method+" with handlers for the events this call raises, delivered before it returns.")
		}
	}
}

func (g *generator) method(receiver, method, params, out, kind, op, in, handlers, doc string) {
	g.comment("", doc)
	if handlers == "" {
		handlers = "nil"
	}
	if out == "" {
		g.printf("func (x *%s) %s(%s) error {\n\treturn x.o.CallWith(%q, %s, nil, %s)\n}\n\n", receiver, method, params, op, in, handlers)
		return
	}
	g.printf("func (x *%s) %s(%s) (%s, error) {\n\tvar out %s\n\terr := x.o.CallWith(%q, %s, &out, %s)\n\treturn out, err\n}\n\n",
		receiver, method, params, out, out, op, in, handlers)
}

// handlers writes a struct of handler funcs for some events, and its conversion to library.Handlers.
func (g *generator) handlers(name, what string, events map[string]library.EventDescription, kinds []string) {
	g.printf("// %s serve %s. A nil one is no handler.\n", name, what)
	g.printf("type %s struct {\n", name)
	for _, k := range kinds {
		e := events[k]
		field := goName(k)
		switch e.Answer {
		case "allow":
			g.comment("\t", field+" answers "+k+": nil allows."+aboutSuffix(e.About))
			g.printf("\t%s func(data json.RawMessage) error\n", field)
		case "result":
			g.comment("\t", field+" answers "+k+" with a payload, or an error passed on as the public error when it marshals to an object with a code."+aboutSuffix(e.About))
			g.printf("\t%s func(data json.RawMessage) (any, error)\n", field)
		default:
			g.comment("\t", field+" is told of "+k+"."+aboutSuffix(e.About))
			g.printf("\t%s func(data json.RawMessage)\n", field)
		}
	}
	g.printf("}\n\n")
	g.printf("func (h %s) handlers() library.Handlers {\n\tm := library.Handlers{}\n", name)
	for _, k := range kinds {
		field := goName(k)
		g.printf("\tif f := h.%s; f != nil {\n", field)
		switch events[k].Answer {
		case "allow":
			g.printf("\t\tm[%q] = func(d json.RawMessage) (any, error) { return nil, f(d) }\n", k)
		case "result":
			g.printf("\t\tm[%q] = f\n", k)
		default:
			g.printf("\t\tm[%q] = func(d json.RawMessage) (any, error) { f(d); return nil, nil }\n", k)
		}
		g.printf("\t}\n")
	}
	g.printf("\treturn m\n}\n\n")
}

func (g *generator) ensureRaw() {
	if g.types["raw()"] != "" {
		return
	}
	g.types["raw()"] = "raw"
	g.decls.WriteString("// raw is an input given as JSON: nil sends {}.\nfunc raw(in json.RawMessage) any {\n\tif len(in) == 0 {\n\t\treturn nil\n\t}\n\treturn in\n}\n\n")
}

type schema struct {
	Type       any                        `json:"type"`
	Properties map[string]json.RawMessage `json:"properties"`
	Required   []string                   `json:"required"`
	Items      json.RawMessage            `json:"items"`
	Enum       []any                      `json:"enum"`
	Const      any                        `json:"const"`
}

// schemaType is the Go type for a JSON Schema: a struct named name when it names properties, a
// scalar for a scalar type, json.RawMessage otherwise. An output that is anything ({}) or nothing is
// "" (the method returns only an error). For a config, a const property (the object's kind, which
// the runtime sets) is left out.
func (g *generator) schemaType(name string, raw json.RawMessage, config bool) string {
	var s schema
	if len(raw) == 0 || json.Unmarshal(raw, &s) != nil {
		if strings.HasSuffix(name, "Output") {
			return ""
		}
		return "json.RawMessage"
	}
	if s.Type == nil && s.Enum == nil && s.Properties == nil && strings.HasSuffix(name, "Output") {
		return ""
	}
	if len(s.Properties) == 0 {
		return scalar(s)
	}
	if t, ok := g.types[name]; ok {
		return t
	}
	g.types[name] = name
	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// %s is the JSON object the description gives for it.\ntype %s struct {\n", name, name)
	for _, p := range sortedKeys(s.Properties) {
		var ps schema
		_ = json.Unmarshal(s.Properties[p], &ps)
		if config && ps.Const != nil {
			continue
		}
		field := goName(p)
		t := g.schemaType(name+field, s.Properties[p], false)
		if t == "" {
			t = "json.RawMessage"
		}
		tag := p
		if !required[p] {
			tag += ",omitempty"
			if g.types[t] == t {
				t = "*" + t // an optional object: omitempty leaves a nil one out
			}
		}
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", field, t, tag)
	}
	b.WriteString("}\n\n")
	g.decls.WriteString(b.String())
	return name
}

func scalar(s schema) string {
	t, _ := s.Type.(string)
	if t == "" && len(s.Enum) > 0 {
		if _, ok := s.Enum[0].(string); ok {
			return "string"
		}
	}
	switch t {
	case "string":
		return "string"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		var items schema
		if json.Unmarshal(s.Items, &items) == nil {
			if it, _ := items.Type.(string); it == "string" {
				return "[]string"
			}
		}
		return "[]json.RawMessage"
	}
	return "json.RawMessage"
}

var initialisms = map[string]string{"id": "ID", "ids": "IDs", "abi": "ABI", "json": "JSON", "url": "URL", "os": "OS", "ms": "MS", "sha256": "SHA256"}

// goName is an exported Go name for a description's name: descriptor.validate is
// DescriptorValidate, list_unverified ListUnverified, timeout_ms TimeoutMS.
func goName(s string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		if up, ok := initialisms[strings.ToLower(part)]; ok {
			b.WriteString(up)
			continue
		}
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	name := b.String()
	if name == "" || !unicode.IsLetter([]rune(name)[0]) {
		name = "X" + name
	}
	return name
}

func aboutSuffix(about string) string {
	if about == "" {
		return ""
	}
	return " " + about
}

func wrap(text string, width int) []string {
	var lines []string
	line := ""
	for _, w := range strings.Fields(text) {
		if line != "" && len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = w
			continue
		}
		if line != "" {
			line += " "
		}
		line += w
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
