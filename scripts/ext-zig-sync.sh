#!/usr/bin/env bash
# Regenerates pkg/ext-zig/csrc from lib/plugin, or with --check verifies that it is current.
#
# A Zig package is the files its build.zig.zon lists, and a consumer fetches nothing else. The SDK
# compiles the C engine's portable guest core (build.zig), so the package carries the sources it is
# built from: the files `core_sources` names in lib/plugin/CMakeLists.txt, every header they may
# include, and the vendored parser's licence. lib/plugin stays the canonical home (the iOS, Android,
# Rust and cgoengine bindings build from it); csrc is a copy, and scripts/ext-zig-release.sh refuses
# to stage a package whose copy differs. Run this after changing lib/plugin and commit both.
#
# Usage: scripts/ext-zig-sync.sh [--check]
set -euo pipefail
cd "$(dirname "$0")/.."
check=0
case "${1:-}" in
  "") ;;
  --check) check=1 ;;
  *) echo 'usage: scripts/ext-zig-sync.sh [--check]' >&2; exit 2 ;;
esac
src=lib/plugin
dst=pkg/ext-zig/csrc

core="$(sed -n 's/^set(core_sources \(.*\))$/\1/p' "$src/CMakeLists.txt")"
[[ -n "$core" ]] || { echo "$src/CMakeLists.txt has no one-line set(core_sources ...)" >&2; exit 1; }
files="$( { for f in $core; do echo "$f"; done; cd "$src" && ls include/*.h src/*.h vendor/yyjson.h vendor/LICENSE vendor/README.md; } | sort -u)"

stage() {
  local out="$1" f
  mkdir -p "$out"
  while IFS= read -r f; do
    [[ -f "$src/$f" ]] || { echo "$src/$f does not exist" >&2; exit 1; }
    mkdir -p "$out/$(dirname "$f")"
    cp "$src/$f" "$out/$f"
  done <<<"$files"
  cat >"$out/README.md" <<'EOF'
# The C engine's guest core, as ext-zig is built from it

Generated by `scripts/ext-zig-sync.sh` from `lib/plugin`. Do not edit: change `lib/plugin`, run the
script and commit both. The files are those `core_sources` names in `lib/plugin/CMakeLists.txt`, every
header they may include, and the vendored parser's licence.
EOF
}

if ((check)); then
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  stage "$work/csrc"
  if ! diff -r "$work/csrc" "$dst" >&2; then
    echo "$dst differs from $src: run scripts/ext-zig-sync.sh and commit both" >&2
    exit 1
  fi
  echo "$dst matches $src"
else
  rm -rf "$dst"
  stage "$dst"
  echo "synced $src -> $dst ($(find "$dst" -type f | wc -l | tr -d ' ') files)"
fi
